'use strict';
const assert = require('node:assert/strict');
const { inventoryFixture, grantItem } = require('./helpers/inventory-fixture');
const { playerStateView } = require('../core/durable-state-view-engine');
async function main() {
  const { nextStep, receiptText, itemName, itemDescription, actionDescriptions, displayName, waitingReceiptId, operationalMessage, readDiagnosticsRows } = await import('../client/durable/guide.mjs');
  const world = inventoryFixture(), hero = world.entities['hero-one'];
  const state = () => playerStateView(world, 1, 'one');
  assert.equal(nextStep(state()).type, 'work');
  assert.equal(nextStep(state(), { stale: true }).kind, 'refresh', 'do not recommend new actions from a failed refresh');
  assert.equal(nextStep(state(), { stale: true, pending: { id: 'same-id' } }).kind, 'retry', 'preserve recovery of the original request');
  assert.equal(nextStep(state(), { pending: { id: 'same-id' } }).kind, 'retry');
  assert.equal(nextStep(state(), { waitingId: 'existing-command' }).kind, 'refresh');
  const acknowledged = { id: 'acknowledged-before-refresh-failed', status: 'pending', result: null };
  assert.equal(nextStep(state(), { waitingId: waitingReceiptId(acknowledged) }).kind, 'refresh', 'a failed state/history refresh cannot turn an acknowledged pending command into a new action');
  assert.equal(waitingReceiptId({ id: 'a', status: 'applied', result: { status: 'accepted' } }), 'a');
  assert.equal(waitingReceiptId({ id: 'a', status: 'applied', result: { status: 'completed' } }), null);
  hero.stats.energy = 0; assert.equal(nextStep(state()).type, 'rest');
  hero.stats.energy = 100;
  const completed = new Set(['work']);
  const purchase = nextStep(state(), { completed });
  assert.equal(purchase.type, 'buy_item'); assert.equal(purchase.payload.quantity, 1);
  assert.ok(state().inventory.shops.some(shop => shop.id === purchase.payload.shopId && shop.stock.some(item => item.definitionId === purchase.payload.definitionId && item.type === 'equipment' && item.quantity > 0)));
  hero.resources.currency = 0; assert.equal(nextStep(state(), { completed }).type, 'work');
  const item = grantItem(world, 'entity', hero.id, purchase.payload.definitionId, 1);
  assert.equal(nextStep(state(), { completed }).type, 'equip_item');
  item.equipped = true; assert.equal(nextStep(state(), { completed }).kind, 'actions');
  world.players.byId.one.controlMode = 'observer'; assert.equal(nextStep(state(), { completed }).kind, 'characters');
  assert.match(receiptText({ status: 'applied', result: { type: 'create_character', status: 'completed', outcome: { value: { name: '新旅人' } } } }), /新旅人.*已建立/);
  assert.match(receiptText({ status: 'applied', result: { type: 'move', status: 'rejected', outcome: { reason: 'not_neighbors' } } }), /不相邻/);
  assert.match(receiptText({ status: 'applied', result: { type: 'switch_character', status: 'rejected', outcome: { reason: 'character_not_owned' } } }), /自己拥有/);
  assert.match(receiptText({ status: 'pending', result: { status: 'completed' } }, 'work'), /等待世界结算/);
  assert.match(receiptText({ status: 'applied', result: { status: 'accepted' } }, 'work'), /尚未确认完成/);
  assert.match(receiptText({ status: 'applied', result: { status: 'rejected', outcome: { reason: 'insufficient_energy' } } }), /先休息/);
  const work = { status: 'applied', result: { status: 'completed', outcome: { actionType: 'work', value: { resource: 'currency', amount: 17, energyCost: 4 } } } };
  assert.match(receiptText(work), /货币 \+17/); assert.match(receiptText(work), /体力消耗 4/);
  assert.match(actionDescriptions({ workYield: 17, workEnergy: 4, workResource: 'currency' }).work, /17 货币/);
  assert.equal(itemName({ definitionId: 'wooden_sword', name: 'Wooden Sword' }), '木剑');
  assert.equal(itemName({ definitionId: 'wooden_sword', name: '定制长剑' }), '定制长剑');
  assert.match(itemDescription({ type: 'equipment', stats: { energy: 2 } }), /体力上限 \+2/);
  assert.equal(displayName('founder_1'), '旅人 2');
  assert.equal(operationalMessage({ service: null }).warning, true);
  const operation = { service: { ready: true, runtime: { failureKind: null } }, audit: { failures: 0, durable: true }, queue: { worldCapacityAvailable: true } };
  assert.equal(operationalMessage(operation).warning, false);
  assert.match(operationalMessage(operation).text, /手动再次检查/, 'one healthy observation must not claim sustained progress');
  operation.audit.durable = false; assert.match(operationalMessage(operation).title, /尚未持久化/); operation.audit.durable = true;
  operation.audit.failures = 1; assert.match(operationalMessage(operation).title, /审计需要检查/);
  operation.audit.failures = 0; operation.queue.worldCapacityAvailable = false; assert.match(operationalMessage(operation).title, /队列已满/);
  operation.service.ready = false;
  for (const failureKind of ['revision_conflict', 'heartbeat_stale', 'worker_failed', 'database_unavailable', 'runtime_failed']) {
    operation.service.runtime.failureKind = failureKind; assert.equal(operationalMessage(operation).warning, true);
  }
  operation.service.stopping = true; assert.match(operationalMessage(operation).title, /正在停止/);
  assert.deepEqual(readDiagnosticsRows(null), [['读取诊断', '未接入']]);
  const diagnosticRows = readDiagnosticsRows({ requests: 5, active: 1, duration: { lastMs: 10, maxMs: 30, totalMs: 60 },
    lastPayload: { bytes: 1048576, fetchMs: 1000, restoreMs: 100 }, lastFailure: { kind: 'timeout', phase: 'payload', ageMs: 3100 } });
  assert.equal(diagnosticRows.find(row => row[0] === '平均读取耗时')[1], '15 毫秒');
  assert(diagnosticRows.some(row => row[1] === '1.00 MB'));
  assert.match(diagnosticRows.at(-1)[1], /数据库超时.*下载存档.*3 秒前/);
  assert(!JSON.stringify(readDiagnosticsRows({ duration: { totalMs: Infinity }, lastFailure: { kind: 'secret-token', phase: '__proto__' } })).includes('secret-token'));
  console.log('durable console guide passed: real rules, pending/rejected outcomes, affordable equipment, observer and low-energy recovery');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
