'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const engine = require('..');
const { DEFAULT_SPECIES } = require('../core/species-engine');
const { createTemplateValidator } = require('../shared/template-validation');
const sample = require('../templates/river-valley.json');
const clone = v => JSON.parse(JSON.stringify(v));
async function main() {
  const { createWorkbench, nextId, locationReferences, entityReferences } = await import('../client/durable/workbench-model.mjs');
  const validator = createTemplateValidator(Object.keys(DEFAULT_SPECIES));
  const model = createWorkbench(validator,sample), initial = model.serialize();
  model.edit(t => { t.name = '自定义河谷'; t.playerRules.workYield = 23; t.definition.locations[0].name = '<img src=x onerror=alert(1)>'; });
  const exported = JSON.parse(model.serialize()), world = engine.createEngineWorldFromTemplate(exported);
  assert.equal(world.locations['river-village'].name,'<img src=x onerror=alert(1)>');
  assert.equal(engine.playerStateView(world,1,'observer').actionRules.workYield,23);
  assert.deepEqual(exported.templates[0].definition.organizations,sample.templates[0].definition.organizations,'uneditable fields survive form changes');
  model.edit(t => t.playerRules.workYield = 0); assert.throws(() => model.serialize());
  assert.equal(JSON.parse(model.serialize(false)).templates[0].playerRules.workYield,0);
  model.undo(); assert.equal(model.snapshot().validation.valid,true); model.undo(); assert.equal(model.serialize(),initial);
  const before = model.serialize(); assert.equal(model.load('{').valid,false); assert.equal(model.serialize(),before);
  const duplicate = clone(sample); duplicate.templates[0].definition.connections.push(['pine-forest','river-village']);
  assert.equal(model.load(JSON.stringify(duplicate)).valid,false); assert.equal(model.serialize(),before);
  const pack = clone(sample); pack.templates.push({...clone(pack.templates[0]),id:'second',name:'第二个世界'});
  assert.equal(model.load(JSON.stringify(pack)).needsSelection,true); assert.equal(model.serialize(),before);
  assert.equal(model.load(JSON.stringify(pack),'second').valid,true); model.edit(t => t.name = '只修改第二个');
  assert.equal(JSON.parse(model.serialize()).templates[0].name,sample.templates[0].name);
  assert.equal(JSON.parse(model.serialize()).templates[1].name,'只修改第二个');
  pack.templates[0].definition.connections.push(['missing','pine-forest']); assert.equal(model.load(JSON.stringify(pack),'second').valid,false);
  assert.equal(model.inspectText(' '.repeat(1024*1024+1)).valid,false);
  assert.equal(model.load(JSON.stringify({id:'blank',name:'空白',definition:{locations:[{id:'home'}]}})).valid,true);
  assert.equal(engine.createEngineWorldFromTemplate(JSON.parse(model.serialize())).players.byId.observer.observerLocationId,'home');
  model.markSaved(); assert.equal(model.snapshot().dirty,false); model.edit(t => t.name = '更改'); assert.equal(model.snapshot().dirty,true);
  assert.equal(nextId([{id:'place-1'},{id:'place-3'}],'place'),'place-2');
  assert(locationReferences(sample.templates[0],'river-village') > 0); assert(entityReferences(sample.templates[0],'valley-elder') > 0);
  assert.equal(locationReferences(sample.templates[0],'missing'),0);
  const blank = { id:'blank', name:'空白', definition:{ locations:[{id:'home'},{id:'away'}] } };
  assert.equal(locationReferences(blank,'home'),1,'implicit observer start is a protected reference');
  assert.equal(engine.createEngineWorldFromTemplate(blank).players.byId.observer.observerLocationId,'home');
  blank.observerLocationId = 'away';
  assert.equal(locationReferences(blank,'home'),0,'old start can be removed after choosing another start');
  assert.equal(locationReferences(blank,'away'),1);
  const source = fs.readFileSync(path.join(__dirname,'../shared/template-validation.js'),'utf8');
  const context = vm.createContext({TextEncoder}); vm.runInContext(source,context);
  const cases = [sample,duplicate,null,JSON.parse('{"__proto__":{}}'),{id:'bad',name:'坏配置',definition:{locations:[{id:'constructor'}]}},clone(sample)];
  cases[5].templates[0].definition.entities[0].id = 'observer_character_1';
  for (const input of cases) {
    context.text = JSON.stringify(input); context.ids = JSON.stringify(Object.keys(DEFAULT_SPECIES));
    const browser = vm.runInContext('JSON.stringify(PhyrexTemplateValidation.createTemplateValidator(JSON.parse(ids)).validateEngineTemplate(JSON.parse(text)))',context);
    assert.deepEqual(JSON.parse(browser),engine.validateEngineTemplate(input),'browser and SDK must share identical validation results');
  }
  const app = fs.readFileSync(path.join(__dirname,'../client/durable/workbench.mjs'),'utf8');
  assert(!/innerHTML|localStorage|sessionStorage|\.eval\(/.test(app));
  assert.equal((app.match(/\bfetch\(/g) || []).length,1,'only the public static catalog is fetched');
  assert(app.includes("fetch('/console/template-catalog.json'"));
  console.log('template workbench passed: export-to-engine, atomic import, whole-pack selection, undo, reference guards and browser/Node parity');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
